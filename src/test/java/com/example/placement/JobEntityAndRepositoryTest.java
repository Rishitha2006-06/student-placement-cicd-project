package com.example.placement;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.autoconfigure.orm.jpa.DataJpaTest;
import org.springframework.test.context.ActiveProfiles;

import java.util.List;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;

@DataJpaTest
@ActiveProfiles("test")
class JobEntityAndRepositoryTest {

    @Autowired
    private JobRepository jobRepository;

    @Autowired
    private JobApplicationRepository applicationRepository;

    @Test
    @DisplayName("Should create and retrieve a Job entity successfully")
    void testCreateAndFindJob() {
        Job job = new Job("Software Engineer", "Google", "Bangalore, India", "B.Tech CSE/IT with 7.5+ CGPA");
        Job saved = jobRepository.save(job);

        assertNotNull(saved.getId(), "Job ID should be generated by the database");
        assertEquals("Software Engineer", saved.getTitle());
        assertEquals("Google", saved.getCompany());
        assertEquals("Bangalore, India", saved.getLocation());
        assertEquals("B.Tech CSE/IT with 7.5+ CGPA", saved.getEligibility());

        Optional<Job> found = jobRepository.findById(saved.getId());
        assertTrue(found.isPresent(), "Job should be found by ID");
        assertEquals("Google", found.get().getCompany());
    }

    @Test
    @DisplayName("Should update Job fields correctly")
    void testUpdateJob() {
        Job job = new Job("Analyst", "Deloitte", "Hyderabad", "Any Graduate");
        Job saved = jobRepository.save(job);

        saved.setTitle("Senior Analyst");
        saved.setLocation("Remote");
        jobRepository.save(saved);

        Job updated = jobRepository.findById(saved.getId()).orElseThrow();
        assertEquals("Senior Analyst", updated.getTitle());
        assertEquals("Remote", updated.getLocation());
    }

    @Test
    @DisplayName("Should save JobApplications linked to a Job")
    void testSaveApplicationsForJob() {
        Job job = jobRepository.save(new Job("Cloud Associate", "AWS", "Hyderabad", "B.Tech"));

        JobApplication app1 = new JobApplication("Rishi", "rishi@example.com", job);
        JobApplication app2 = new JobApplication("Alex", "alex@example.com", job);

        applicationRepository.save(app1);
        applicationRepository.save(app2);

        List<JobApplication> all = applicationRepository.findAllByOrderByAppliedAtDesc();
        assertFalse(all.isEmpty());
        assertTrue(all.stream().anyMatch(a -> a.getStudentName().equals("Rishi")));
        assertTrue(all.stream().anyMatch(a -> a.getStudentName().equals("Alex")));
    }
}
